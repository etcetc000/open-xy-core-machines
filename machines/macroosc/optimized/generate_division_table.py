"""Generate one shared table of exact reciprocal lower bounds."""
import argparse
from pathlib import Path
HERE=Path(__file__).resolve().parent
def generated():
    values=[(1<<61)//((index+513)<<21) for index in range(512)]
    header="// Generated by optimized/generate_division_table.py.\n#pragma once\n#include <stdint.h>\nnamespace macroosc {\nextern const int32_t reciprocal_seed[512];\n}\n"
    lines=['// Generated by optimized/generate_division_table.py.', '#include "division_table.hpp"',
           'namespace macroosc {', 'const int32_t reciprocal_seed[512] = {']
    for i in range(0,len(values),8):
        lines.append('  '+', '.join(str(v) for v in values[i:i+8])+',')
    source='\n'.join(lines+['};','}'])+'\n'
    return {'division_table.hpp':header.encode(),'division_table.cpp':source.encode()}
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for name,expected in generated().items():
        target=HERE/name
        if args.check:
            if target.read_bytes().replace(b'\r\n',b'\n')!=expected:raise ValueError('Division seed file differs: '+name)
        else:target.write_bytes(expected)
