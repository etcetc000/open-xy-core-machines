"""Generate exact byte-wave interpolation using the SDK fractional multiply."""
import argparse
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent

def generated():
    source = (HERE.parent/'vendor/stmlib/utils/dsp.h').read_bytes().replace(b'\r\n', b'\n')
    expected = 'c0fad7f6b5b20f053d184614a35baf595e41f1394db53f80ac742d7467dbbe1b'
    if hashlib.sha256(source).hexdigest() != expected:
        raise ValueError('Original DSP header changed')
    source = source.decode()
    original = source
    source = source.replace('#include "stmlib/stmlib.h"', '#include "stmlib/stmlib.h"\n#include <opxy/q31.hpp>')
    old = '''  return (a << 8) + \\
      ((b - a) * static_cast<int32_t>(phase & 0xffffff) >> 16) - 32768;'''
    new = '''  // The original 32-bit product may wrap; its high half differs from
  // the wide product only by multiples of 65536, discarded by int16_t return.
  return (a << 8) + opxy::q31::multiply((b - a) * 32768,
      static_cast<int32_t>(phase & 0xffffff)) - 32768;'''
    if source.count(old) != 1:
        raise ValueError('Byte interpolation shape changed')
    source = source.replace(old, new)
    begin = source.index('inline int16_t Crossfade(\n    const uint8_t* table_a,', source.index('inline int16_t Mix'))
    end = source.index('\n}', begin) + 2
    body = source[begin:end]
    old = 'return a + ((b - a) * static_cast<int32_t>(balance) >> 16);'
    if body.count(old) != 1:
        raise ValueError('Byte crossfade shape changed')
    body = body.replace(old, 'return a + opxy::q31::multiply((b - a) * 32768, static_cast<int32_t>(balance));')
    interpolation_begin = source.index('inline int16_t Interpolate824(const uint8_t* table, uint32_t phase) {')
    interpolation_end = source.index('\n}', interpolation_begin) + 2
    interpolation = source[interpolation_begin:interpolation_end].replace('Interpolate824(', 'MacroInterpolateByte(')
    body = body.replace('Crossfade(', 'MacroCrossfadeByte(').replace('Interpolate824(', 'MacroInterpolateByte(')
    extra = (interpolation+'\n'+body).replace('inline int16_t', 'inline __attribute__((always_inline)) int16_t')
    original = original.replace('#include "stmlib/stmlib.h"', '#include "stmlib/stmlib.h"\n#include <opxy/q31.hpp>')
    source = original.replace('}  // namespace stmlib', extra+'\n\n}  // namespace stmlib')
    source = source.replace('#ifndef STMLIB_UTILS_DSP_H_\n#define STMLIB_UTILS_DSP_H_', '#pragma once').replace('#endif  // STMLIB_UTILS_DSP_H_', '')
    return ('// Generated by optimized/generate_dsp.py. Original MIT notice follows.\n'+source).encode()

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = HERE/'stmlib/utils/dsp.h'
    data = generated()
    if args.check:
        if output.read_bytes().replace(b'\r\n', b'\n') != data:
            raise ValueError('DSP overlay does not match generator')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_bytes(data)
