"""Specialize fixed-mode drum filters without changing their arithmetic or state."""
import argparse
import hashlib
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def generated():
    raw = (HERE.parent / 'vendor/braids/svf.h').read_bytes().replace(b'\r\n', b'\n')
    if hashlib.sha256(raw).hexdigest() != '17fe7788f2b0da209d0c879a458bd2ef61537666403166f37333dacfe7e090ee':
        raise ValueError('Original SVF changed; review specialization')
    source = raw.decode()
    begin = source.index('    if (dirty_) {', source.index('inline int32_t Process('))
    end = source.index('    int32_t f = f_;', begin)
    prepare = source[begin:end]
    # Only the fixed-mode drum setup benefits from the packed loads. The
    # general Process path (Kick's changing pitch and punch) stays unchanged.
    for name in ('cutoff', 'damp'):
        prepare = prepare.replace(
            'stmlib::Interpolate824(lut_svf_' + name + ',',
            'macroosc::paired_u824(macroosc::svf_' + name + '_pairs,')
    source = source.replace('#include "braids/resources.h"',
                            '#include "braids/resources.h"\n#include "optimized/packed_tables.hpp"')
    extra = '''  // The drum callers keep frequency, resonance, mode and zero punch
  // fixed within a render call. Keep the original arithmetic and clipping.
  inline void Prepare() {
''' + prepare + '''  }
  template<SvfMode Mode> inline int32_t ProcessNoPunch(int32_t in) {
    const int32_t notch = in - (bp_ * damp_ >> 15);
    lp_ += f_ * bp_ >> 15;
    CLIP(lp_)
    const int32_t hp = notch - lp_;
    bp_ += f_ * hp >> 15;
    CLIP(bp_)
    return Mode == SVF_MODE_BP ? bp_ : (Mode == SVF_MODE_HP ? hp : lp_);
  }

'''
    # Deferring the clipped BP write lets the compiler use min/max instead
    # of branches and conditional member stores in Snare's crowded loop.
    # Cymbal is faster with the original method, so keep this opt-in.
    local = extra[extra.index('  template<SvfMode Mode>'):]
    local = local.replace('ProcessNoPunch(', 'ProcessNoPunchLocal(')
    local = local.replace('    bp_ += f_ * hp >> 15;\n    CLIP(bp_)',
                          '    int32_t next_bp = bp_ + (f_ * hp >> 15);\n'
                          '    CLIP(next_bp)\n    bp_ = next_bp;')
    local = local.replace('SVF_MODE_BP ? bp_', 'SVF_MODE_BP ? next_bp')
    source = source.replace(' private:', extra + local + ' private:', 1)
    # Frequency and resonance are independent inputs. A pitch-only update
    # cannot invalidate the damping coefficient, and vice versa. Keep both
    # flags in the existing one-byte dirty field (no object layout growth).
    source = source.replace('  bool dirty_;', '  uint8_t dirty_;')
    source = source.replace('    dirty_ = true;', '    dirty_ = 3;', 1)
    source = source.replace('    dirty_ = dirty_ || (frequency_ != frequency);',
                            '    dirty_ |= frequency_ != frequency ? 1 : 0;')
    source = source.replace('    dirty_ = true;', '    dirty_ |= 2;')
    source = source.replace('    resonance_ = resonance;\n    dirty_ |= 2;',
                            '    dirty_ |= resonance_ != resonance ? 2 : 0;\n'
                            '    resonance_ = resonance;')
    lines = source.splitlines()
    for index, line in enumerate(lines):
        if '      f_ = ' in line:
            lines[index] = line.replace('      ', '      if (dirty_ & 1) ', 1)
        elif '      damp_ = ' in line:
            lines[index] = line.replace('      ', '      if (dirty_ & 2) ', 1)
    source = '\n'.join(lines) + '\n'
    source = source.replace('#ifndef BRAIDS_SVF_H_\n#define BRAIDS_SVF_H_', '#pragma once')
    source = source.replace('#endif  // BRAIDS_SVF_H_', '')
    return ('// Generated by optimized/generate_filter.py. Original MIT notice follows.\n' + source).encode()


def transform_digital(source):
    # Snare initializes all three filters in BP mode. Cymbal initializes BP/HP.
    # Init() sets punch to zero; neither renderer subsequently changes it.
    for name, modes in [('RenderSnare', ['BP', 'BP', 'BP']), ('RenderCymbal', ['BP', 'HP'])]:
        match = re.search(r'void DigitalOscillator::' + name + r'\([^{}]*\{.*?\n\}', source, re.S)
        if not match:
            raise ValueError('Missing drum renderer ' + name)
        body = match[0]
        if body.count('  while (size') != 1:
            raise ValueError('Drum render loop changed')
        prepare = ''.join('  svf_[' + str(i) + '].Prepare();\n' for i in range(len(modes))) + '\n'
        body = body.replace('  while (size', prepare + '  while (size')
        for i, mode in enumerate(modes):
            call = 'svf_[' + str(i) + '].Process('
            if body.count(call) != 1:
                raise ValueError('Drum filter call changed')
            body = body.replace(call, 'svf_[' + str(i) + '].ProcessNoPunch<SVF_MODE_' + mode + '>(')
        source = source[:match.start()] + body + source[match.end():]
    return source


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = HERE / 'braids/svf.h'
    data = generated()
    if args.check:
        if path.read_bytes().replace(b'\r\n', b'\n') != data:
            raise ValueError('Prepared filter differs from reviewed transformation')
    else:
        path.write_bytes(data)
