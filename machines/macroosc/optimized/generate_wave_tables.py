"""Generate the shared aligned wave segments and exact wavetable renderers."""
import argparse
import hashlib
from pathlib import Path
import re
import chord_render
import flute_jet_render

HERE = Path(__file__).resolve().parent

CHORD_RENDERERS = ('RenderWaveParaphonic',)


def transform_digital(source):
    for name in ('RenderWavetables','RenderWaveMap'):
        match=re.search(r'void DigitalOscillator::'+name+r'\([^{}]*\{.*?\n\}',source,re.S)
        if not match:raise ValueError('Missing wave renderer '+name)
        body=match[0].replace('const uint8_t* wave','const uint32_t* wave')
        body=body.replace('wt_waves','macroosc::wave_compact').replace('* 129','* 128')
        body=body.replace('MacroCrossfadeByte(','macroosc::wave_crossfade(').replace('Crossfade(','macroosc::wave_crossfade(')
        # Digital renderers receive only the adapter's all-zero sync array.
        body=body.replace('if (*sync++)','if (0)')
        if name=='RenderWaveMap':
            body=body.replace('macroosc::wave_crossfade(', 'macroosc::wave_crossfade_wrapped(')
            body=re.sub(r'\bphase_\b','phase',body)
            body=body.replace('  uint32_t phase_increment = phase_increment_ >> 1;',
                '  uint32_t phase=phase_;\n  uint32_t phase_increment = phase_increment_ >> 1;')
            begin=body.index('  while (size--) {')
            expression=re.search(r'    sample = (.*?);',body[begin:],re.S)
            if not expression:raise ValueError('Wave Map oversampling changed')
            body=body[:begin]+'''  // Preserve each half-sample's rounding before addition.
  // The adapter limits every render call to24frames, hence48 scratch samples.
  int16_t oversampled[48];
  for(unsigned i=0;i<size*2;++i) {
    phase+=phase_increment;
    oversampled[i]='''+expression[1]+''';
  }
  for(unsigned i=0;i<size;++i)buffer[i]=static_cast<int32_t>(oversampled[2*i])+oversampled[2*i+1];
  phase_=phase;
}
'''
        source=source[:match.start()]+body+source[match.end():]
    source = chord_render.transform(source)
    for old, new in [
        ('wt_waves + wave_line[previous_parameter_[0] >> 9] * 129', 'macroosc::wave_compact + macroosc::wave_line_indices[previous_parameter_[0] >> 9] * 128'),
        ('wt_waves + wave_line[scan >> 10] * 129', 'macroosc::wave_compact + macroosc::wave_line_indices[scan >> 10] * 128'),
        ('wt_waves + wave_line[(scan >> 10) + 1] * 129', 'macroosc::wave_compact + macroosc::wave_line_indices[(scan >> 10) + 1] * 128'),
    ]:
        if source.count(old) != 1:
            raise ValueError('Wave Line lookup changed')
        source = source.replace(old, new)
    source, count = re.subn(r'static const uint8_t wave_line\[\] = \{.*?\};', '', source, flags=re.S)
    if count != 1 or 'wt_waves' in source:
        raise ValueError('Unexpected residual wavetable references')
    start=source.index('void DigitalOscillator::RenderWaveLine(')
    end=source.index('\n#define SEMI',start)
    body=source[start:end].replace('const uint8_t* wave','const uint32_t* wave')
    source=source[:start]+body+source[end:]
    return '#include "optimized/wave_compact.hpp"\n'+source


def generated():
    raw = (HERE.parent/'vendor/braids/resources.cc').read_bytes().replace(b'\r\n', b'\n')
    if hashlib.sha256(raw).hexdigest() != '6d5469d50ad29c6546dee111a9b1e3f4669be35b1f8718b1d0326239d1a9e74a':
        raise ValueError('Original resources changed')
    source = raw.decode()
    match = re.search(r'const uint8_t wt_waves\[\] = \{(.*?)\};', source, re.S)
    values = list(map(int, re.findall(r'\d+', match[1])))
    if len(values) != 256 * 129:
        raise ValueError('Unexpected wave table extent')
    aligned = []
    for wave in range(256):
        samples = values[wave * 129:(wave + 1) * 129]
        differences = [b-a for a, b in zip(samples, samples[1:])]
        aligned.extend((((a<<8)-32768)&65535)|((delta&65535)<<16) for a,delta in zip(samples,differences))
    digital = (HERE.parent/'vendor/braids/digital_oscillator.cc').read_bytes().replace(b'\r\n', b'\n')
    if hashlib.sha256(digital).hexdigest() != '6ca164788680d939ade7d1fe91e44a1d1fac9b00cee6a2b34a3e4a25c8bf9ada':
        raise ValueError('Original digital source changed')
    indices = list(map(int, re.findall(r'\d+', re.search(r'static const uint8_t wave_line\[\] = \{(.*?)\};', digital.decode(), re.S)[1])))
    if len(indices) != 64:
        raise ValueError('Wave Line extent changed')
    # The original list lacked the terminal entry used by index+1 at maximum
    # scan. Repeat the last wave, giving that previously undefined read a limit.
    indices.append(indices[-1])
    notice = '// Generated by optimized/generate_wave_tables.py. Original MIT notice follows.\n'
    output = notice+source[:source.index('#include')]+'#include "wave_compact.hpp"\n\nnamespace macroosc {\n'
    for name, kind, data in [('wave_compact', 'uint32_t', aligned), ('wave_line_indices', 'uint8_t', indices)]:
        output += 'const '+kind+' '+name+'['+str(len(data))+'] = {\n'
        for i in range(0, len(data), 16):
            output += '  '+', '.join(str(x) for x in data[i:i+16])+',\n'
        output += '};\n\n'
    output += '}\n'
    resources = notice+source[:match.start()]+'// Samples are supplied by optimized/wave_compact.cpp.\n'+source[match.end():]
    # These exact curves are now supplied by the packed tables. Keep wav_sine
    # because digital modulation still reads its original sample entries.
    for name in ('ws_sine_fold','ws_tri_fold','ws_violent_overdrive',
                 'lut_bell','lut_resonator_coefficient','lut_resonator_scale'):
        resources, count = re.subn(r'const (?:u?int16_t) '+name+r'\[\] = \{.*?\};',
            '// '+name+' is supplied by optimized/packed_tables.cpp.', resources, flags=re.S)
        if count != 1:raise ValueError('Packed-only resource changed: '+name)
    resources = flute_jet_render.transform_resources(resources)
    return {HERE/'wave_compact.cpp': output.encode(), HERE/'resources.cpp': resources.encode()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in generated().items():
        if args.check:
            if path.read_bytes().replace(b'\r\n', b'\n') != data:
                raise ValueError('Generated wavetable data differs: '+path.name)
        else:
            path.write_bytes(data)
