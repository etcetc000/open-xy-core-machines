"""Pack original signed samples with exact adjacent differences, without resampling."""
import argparse
import hashlib
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent

def generated():
    raw = (HERE.parent/'vendor/braids/resources.cc').read_bytes().replace(b'\r\n', b'\n')
    if hashlib.sha256(raw).hexdigest() != '6d5469d50ad29c6546dee111a9b1e3f4669be35b1f8718b1d0326239d1a9e74a':
        raise ValueError('Original resources changed; review derived table provenance')
    source = raw.decode()
    licence = source[:source.index('#include')]
    output = '// Generated by optimized/generate_packed_tables.py. Original MIT notice follows.\n'
    output += licence + '#include "packed_tables.hpp"\n\nnamespace macroosc {\n'
    for old, new in [('wav_sine', 'sine_pairs'), ('ws_sine_fold', 'sine_fold_pairs'), ('ws_tri_fold', 'tri_fold_pairs'), ('ws_moderate_overdrive', 'moderate_pairs'), ('ws_violent_overdrive', 'violent_pairs'), ('lut_svf_cutoff', 'svf_cutoff_pairs'), ('lut_svf_damp', 'svf_damp_pairs'), ('lut_svf_scale', 'svf_scale_pairs'), ('lut_resonator_coefficient', 'resonator_coefficient_pairs'), ('lut_resonator_scale', 'resonator_scale_pairs'), ('lut_bell', 'bell_pairs')]:
        match = re.search(r'const (?:u?int16_t) '+old+r'\[\] = \{(.*?)\};', source, re.S)
        if not match:
            raise ValueError('Missing source table '+old)
        values = list(map(int, re.findall(r'-?\d+', match[1])))
        if len(values) != (129 if old.startswith('lut_resonator_') else 257):
            raise ValueError('Unexpected table extent '+old)
        packed = []
        for a, b in zip(values, values[1:]):
            delta = b-a
            if not ((0 <= a <= 65535 if old.startswith('lut_') else -32768 <= a <= 32767) and -32768 <= delta <= 32767):
                raise ValueError('Sample/slope exceeds signed halfword '+old)
            packed.append((a & 65535) | ((delta & 65535) << 16))
        output += 'const uint32_t '+new+'['+str(len(packed))+'] = {\n'
        for i in range(0, len(packed), 8):
            output += '  '+', '.join('0x%08xu'%v for v in packed[i:i+8])+',\n'
        output += '};\n\n'
        if old == 'wav_sine':
            halves = []
            for a, b in zip(values, values[1:]):
                delta = b-a
                for anchor in (a, b):
                    halves.append((anchor & 65535) | ((delta & 65535) << 16))
            output += 'const uint32_t sine_half_pairs[512] = {\n'
            for i in range(0, len(halves), 8):
                output += '  '+', '.join('0x%08xu'%v for v in halves[i:i+8])+',\n'
            output += '};\n\n'

    return (output+'}  // namespace macroosc\n').encode()

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = HERE/'packed_tables.cpp'
    data = generated()
    if args.check:
        if path.read_bytes().replace(b'\r\n', b'\n') != data:
            raise ValueError('Packed tables do not match generator')
    else:
        path.write_bytes(data)
