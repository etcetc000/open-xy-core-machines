"""Precompute the original integer pitch interpolation, without resampling."""
import argparse
import hashlib
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def generated():
    raw = (HERE.parent / 'vendor/braids/resources.cc').read_bytes().replace(b'\r\n', b'\n')
    if hashlib.sha256(raw).hexdigest() != '6d5469d50ad29c6546dee111a9b1e3f4669be35b1f8718b1d0326239d1a9e74a':
        raise ValueError('Original resources changed; review pitch-table provenance')
    source = raw.decode()
    match = re.search(r'const uint32_t lut_oscillator_increments\[\] = \{(.*?)\};', source, re.S)
    if not match:
        raise ValueError('Missing oscillator increment table')
    values = list(map(int, re.findall(r'\d+', match[1])))
    if len(values) != 97:
        raise ValueError('Unexpected oscillator increment extent')
    table = []
    for pitch in range(1536):
        a, b = values[pitch >> 4], values[(pitch >> 4) + 1]
        product = (b - a) * (pitch & 15)
        if not -(1 << 31) <= product < (1 << 31):
            raise ValueError('Original signed interpolation would overflow')
        table.append(a + (product >> 4))
    output = '// Generated by optimized/generate_pitch_table.py. Original MIT notice follows.\n'
    output += source[:source.index('#include')] + '#include "pitch_table.hpp"\n\nnamespace macroosc {\n'
    output += 'const opxy::u32 pitch_increments[1536] = {\n'
    for i in range(0, len(table), 8):
        output += '  ' + ', '.join(str(x) + 'u' for x in table[i:i + 8]) + ',\n'
    return (output + '};\n}  // namespace macroosc\n').encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = HERE / 'pitch_table.cpp'
    data = generated()
    if args.check:
        if path.read_bytes().replace(b'\r\n', b'\n') != data:
            raise ValueError('Pitch table differs from original integer interpolation')
    else:
        path.write_bytes(data)
